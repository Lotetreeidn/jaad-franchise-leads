// Embeds migrations/*.sql into src/schema.gen.ts so a dashboard-only deploy can create its own tables.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const dir = join(root, "migrations");
const migrations = readdirSync(dir).filter(f => /^\d{4}_.+\.sql$/.test(f)).sort().map(name => ({ name, sql: readFileSync(join(dir, name), "utf8") }));
const body = `// Generated by scripts/gen-migrations.mjs from migrations/*.sql. Do not edit by hand.\nexport const MIGRATIONS: { name: string; sql: string }[] = ${JSON.stringify(migrations, null, 2)};\n`;
writeFileSync(join(root, "src/schema.gen.ts"), body);
console.log(`embedded ${migrations.length} migration(s)`);
